#!/usr/bin/env python3
"""Keep the inventory, PINS.json, true (ADR-0013 item 7).

    tools/pins.py check             the Dockerfile and PINS.json agree, and PINS.json agrees with itself
    tools/pins.py readme [--check]  write the README's table of pins from PINS.json, or fail if it differs
    tools/pins.py moved BASE        the pins whose values differ between PINS.json at git BASE and here, or that
                                    are new here, one per line as `<kind> <tool>`; nothing if none moved

`check` fails when:
  - a build argument's default in the Dockerfile differs from the value PINS.json gives it;
  - the Dockerfile declares a build argument that is neither a pin's nor listed under `not_pins`, since no input
    to the build is left free (ADR-0013 item 1);
  - a pin's digests disagree with each other (the tarball's sha256 and TLAPM_SHA256, the binary's and
    TLAPM_BINARY_SHA256, the jar's and TLA2TOOLS_SHA256, and cvc5's, ethos's and the CPC signature's archives and
    binaries with their build arguments), or a served log does not name the current value;
  - a kept pin's copy is not in its kept release, or cvc5, ethos and the signature are not in one release
    (ADR-0017 items 1 and 4);
  - the method pin's version is not the commit its VENDOR-PIN names.

Standard library only. Changes nothing except, with `readme`, README.md between its two markers.
"""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PINS = os.path.join(ROOT, "PINS.json")
DOCKERFILE = os.path.join(ROOT, "Dockerfile")
README = os.path.join(ROOT, "README.md")
BEGIN = "<!-- pins:begin (generated by tools/pins.py readme from PINS.json; do not edit) -->"
END = "<!-- pins:end -->"


def load(text=None):
    if text is None:
        with open(PINS, encoding="utf-8") as f:
            text = f.read()
    return json.loads(text)


def dockerfile_args():
    """Every ARG in the Dockerfile, with each default it is given (an ARG may be declared in several stages)."""
    args = {}
    with open(DOCKERFILE, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\s*ARG\s+([A-Za-z_][A-Za-z0-9_]*)(?:=(\S*))?\s*$", line)
            if m:
                args.setdefault(m.group(1), set())
                if m.group(2) is not None:
                    args[m.group(1)].add(m.group(2))
    return args


def served_value(pin):
    """What a served-log entry must name for this pin's current value (ADR-0013 item 7)."""
    if pin["tool"] == "apt":
        return ("snapshot", pin["set_by"]["APT_SNAPSHOT"])
    if pin["tool"] == "base":
        return ("sha256", pin["resolved"]["digest"].split(":", 1)[1])
    if "download_sha256" in pin:
        return ("sha256", pin["download_sha256"])
    return None


def check():
    inv = load()
    problems = []
    args = dockerfile_args()
    owned = set(inv.get("not_pins", {}))
    for pin in inv["pins"]:
        for arg, want in pin.get("set_by", {}).items():
            owned.add(arg)
            if arg not in args:
                problems.append(f"{pin['tool']}: the Dockerfile declares no ARG {arg}")
            elif args[arg] != {want}:
                got = ", ".join(sorted(args[arg])) or "no default"
                problems.append(f"{pin['tool']}: ARG {arg} defaults to {got} in the Dockerfile; PINS.json says {want}")
        sv = served_value(pin)
        if sv and pin.get("served"):
            last = pin["served"][-1]
            if last.get(sv[0]) != sv[1]:
                problems.append(f"{pin['tool']}: the last served-log entry names {last.get(sv[0])}, not the current value")
        elif sv:
            problems.append(f"{pin['tool']}: no served log")
    for arg in sorted(set(args) - owned):
        problems.append(f"ARG {arg} is in the Dockerfile but is no pin's and is not under not_pins")
    by_tool = {p["tool"]: p for p in inv["pins"]}
    jar, tlapm = by_tool.get("tla2tools.jar"), by_tool.get("tlapm")
    if jar:
        if jar["download_sha256"] != jar["set_by"]["TLA2TOOLS_SHA256"]:
            problems.append("tla2tools.jar: download_sha256 differs from TLA2TOOLS_SHA256")
        if jar["installed"].get("/opt/tla/tla2tools.jar") != jar["download_sha256"]:
            problems.append("tla2tools.jar: the installed jar's sha256 differs from the download's")
    if tlapm:
        sb = tlapm["set_by"]
        if tlapm["download_sha256"] != sb["TLAPM_SHA256"]:
            problems.append("tlapm: download_sha256 differs from TLAPM_SHA256")
        if tlapm["installed"].get("/opt/tlaps/bin/tlapm") != sb["TLAPM_BINARY_SHA256"]:
            problems.append("tlapm: the installed binary's sha256 differs from TLAPM_BINARY_SHA256")
        if tlapm.get("kept_copy") != sb.get("TLAPM_URL"):
            problems.append("tlapm: TLAPM_URL is not the kept copy (ADR-0005 item 2)")
        if not (tlapm.get("kept_copy") or "").endswith(f"/download/{tlapm.get('kept_release')}/"
                                                       + os.path.basename(tlapm["upstream"])):
            problems.append("tlapm: kept_copy is not the upstream file in the kept_release")
    smt = {t: by_tool.get(t) for t in ("cvc5", "ethos", "CPC signature")}
    for tool, pin, archive, binary, path in (
            ("cvc5", smt["cvc5"], "CVC5_ZIP_SHA256", "CVC5_BINARY_SHA256", "/opt/cvc5/bin/cvc5"),
            ("ethos", smt["ethos"], "ETHOS_ZIP_SHA256", "ETHOS_BINARY_SHA256", "/opt/ethos/bin/ethos"),
            ("CPC signature", smt["CPC signature"], "CVC5_SRC_SHA256", None, None)):
        if pin is None:
            continue
        if pin["download_sha256"] != pin["set_by"].get(archive):
            problems.append(f"{tool}: download_sha256 differs from {archive}")
        if binary and pin["installed"].get(path) != pin["set_by"].get(binary):
            problems.append(f"{tool}: the installed binary's sha256 differs from {binary}")
    if any(smt.values()):
        if not all(smt.values()):
            problems.append("cvc5, ethos and the CPC signature are pinned together or not at all (ADR-0017 item 4)")
        elif len({p["kept_release"] for p in smt.values()}) != 1:
            problems.append("cvc5, ethos and the CPC signature name different kept releases (ADR-0017 item 1)")
        else:
            kept = smt["cvc5"]["set_by"].get("CVC5_KEPT", "")
            release = smt["cvc5"]["kept_release"]
            if not kept.endswith(f"/download/{release}"):
                problems.append(f"cvc5: CVC5_KEPT is not release {release}")
            for tool, pin in smt.items():
                if not pin.get("kept_copy", "").startswith(kept + "/"):
                    problems.append(f"{tool}: kept_copy is not in release {release} (ADR-0017 item 2)")
    for pin in inv["pins"]:
        if "vendor_pin" in pin:
            with open(os.path.join(ROOT, pin["vendor_pin"]), encoding="utf-8") as f:
                commit = re.search(r"^commit (\S+)", f.read(), re.M).group(1)
            short = pin["version"].split()[-1]
            if not commit.startswith(short):
                problems.append(f"{pin['tool']}: version names {short}, the VENDOR-PIN names {commit[:12]}")
    if problems:
        print("pins: PINS.json and the Dockerfile disagree")
        print("\n".join(f"  {p}" for p in problems))
        return 1
    print(f"pins: {len(inv['pins'])} pins in PINS.json agree with the Dockerfile and with themselves; "
          f"{len(args)} build arguments, none left free")
    return 0


def short(digest):
    d = digest.split(":", 1)[-1]
    return f"`{d[:8]}…{d[-4:]}`"


def table():
    inv = load()
    rows = ["| Pin | Kind | What it is | Held to | Served from |", "|---|---|---|---|---|"]
    for p in inv["pins"]:
        sb = p.get("set_by", {})
        if p["tool"] == "tlapm":
            held = (f"tarball sha256 {short(p['download_sha256'])}, binary sha256 {short(sb['TLAPM_BINARY_SHA256'])}, "
                    f"and every one of its {len(p['installed'])} files by sha256")
            source = f"the kept copy, release `{p['kept_release']}` here; upstream `tlaplus/tlapm` `{sb['TLAPM_TAG']}`"
        elif p["tool"] in ("cvc5", "ethos"):
            binary = next(iter(p["installed"].values()))
            held = f"zip sha256 {short(p['download_sha256'])}, binary sha256 {short(binary)}"
            repo = "cvc5/cvc5" if p["tool"] == "cvc5" else "cvc5/ethos"
            source = f"the kept copy, release `{p['kept_release']}` here; upstream `{repo}`"
        elif p["tool"] == "CPC signature":
            held = (f"cvc5's source archive sha256 {short(p['download_sha256'])}, the tree "
                    f"`{p['set_by']['CVC5_CPC_TREE']}`, and each of its {len(p['installed'])} files by sha256")
            source = f"the kept copy, release `{p['kept_release']}` here; upstream `cvc5/cvc5`"
        elif p["tool"] == "tla2tools.jar":
            held = f"sha256 {short(p['download_sha256'])}"
            source = f"upstream `tlaplus/tlaplus` `{sb['TLA2TOOLS_VERSION']}`"
        elif p["tool"] == "base":
            r = p["resolved"]
            held = f"digest {short(r['digest'])} ({r['platform']}, resolved from `{r['tag']}` on {r['date']})"
            source = "Docker Hub"
        elif p["tool"] == "apt":
            held = f"snapshot `{sb['APT_SNAPSHOT']}`; " + ", ".join(f"`{k}` {v}" for k, v in p["packages"].items())
            source = "Ubuntu's snapshot archive"
        elif p["tool"] == "Temurin JRE":
            held = "the base's tag and digest"
            source = "the base"
        elif "vendor_pin" in p:
            held = f"each file's sha256 in [`{p['vendor_pin']}`]({p['vendor_pin']})"
            source = "vendored in this repository"
        else:
            held, source = "", ""
        name = f"`{p['tool']}`" if p["tool"] in ("tla2tools.jar", "tlapm", "apt", "cvc5", "ethos") else p["tool"]
        version = f" {p['version']}" if p.get("version") and p["tool"] not in ("Temurin JRE",) else ""
        rows.append(f"| {name}{version} | {p['kind']} | {p['describes']} | {held} | {source} |")
    return "\n".join(rows)


def readme(check_only):
    with open(README, encoding="utf-8") as f:
        text = f.read()
    if BEGIN not in text or END not in text:
        print(f"pins: README.md has no {BEGIN} … {END} block")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{BEGIN}\n{table()}\n{END}{tail}"
    if new == text:
        print("pins: README.md's table is as PINS.json gives it")
        return 0
    if check_only:
        print("pins: README.md's table differs from PINS.json; run tools/pins.py readme")
        return 1
    with open(README, "w", encoding="utf-8") as f:
        f.write(new)
    print("pins: README.md's table written from PINS.json")
    return 0


def moved(base):
    try:
        old_text = subprocess.run(["git", "-C", ROOT, "show", f"{base}:PINS.json"], check=True,
                                  capture_output=True, text=True).stdout
    except subprocess.CalledProcessError:
        old_text = '{"pins": []}'  # PINS.json is new at this commit: nothing moved
    old = {p["tool"]: p for p in load(old_text)["pins"]}
    for p in load()["pins"]:
        o = old.get(p["tool"])
        # A pin new at this commit is a move too: it changes what the image holds (ADR-0013 item 3).
        if o is None or o.get("set_by") != p.get("set_by") or o.get("version") != p.get("version"):
            print(f"{p['kind']} {p['tool']}")
    return 0


def main(argv):
    if argv[:1] == ["check"]:
        return check()
    if argv[:1] == ["readme"]:
        return readme("--check" in argv[1:])
    if argv[:1] == ["moved"] and len(argv) == 2:
        return moved(argv[1])
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
